#!/usr/bin/env node
// @ts-check
// Writes the content registry: src/content/generated/registry.ts, which imports every record
// file under src/content/data (one record per file, as its default export), in sorted path order.
//
// The registry is generated, never committed, so it can't go stale in a branch or conflict in a
// merge. Git, Prettier and ESLint ignore it. The dev, build, check, typecheck, test and test:e2e
// scripts run this first, and so does Vitest's global setup.
//
//   node scripts/content/registry.mjs            write the registry (only if it changed)
//   node scripts/content/registry.mjs --check    exit 1 if the registry is missing or stale
//   --root <dir>                                 the repo root (default: this script's repo)
//
// Plain Node, no dependencies.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const COMMAND = 'node scripts/content/registry.mjs'
const DATA = 'src/content/data'
const REGISTRY = 'src/content/generated/registry.ts'

function parseArgs(argv) {
  const options = { check: false, root: resolve(dirname(fileURLToPath(import.meta.url)), '../..') }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--check') options.check = true
    else if (arg === '--root' && argv[index + 1]) options.root = resolve(argv[(index += 1)])
    else throw new Error(`Unknown argument: ${arg}\nUsage: ${COMMAND} [--check] [--root <dir>]`)
  }
  return options
}

/** Every record file's path under the data folder, without its extension, sorted. */
function recordPaths(dataDir) {
  if (!existsSync(dataDir)) return []
  return readdirSync(dataDir, { recursive: true, withFileTypes: true })
    .filter(
      (entry) => entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts'),
    )
    .map((entry) => relative(dataDir, join(entry.parentPath, entry.name)).split(sep).join('/'))
    .map((path) => path.slice(0, -'.ts'.length))
    .sort()
}

function render(paths) {
  const imports = paths.map((path, index) => `import record${index} from '../data/${path}'`)
  const entries = paths.map((path, index) => `  { path: '${path}', record: record${index} },`)
  return [
    `// Generated by ${COMMAND} from the files in ${DATA}. Do not edit:`,
    `// add, rename or remove a record file there, then run the command again.`,
    '',
    "import type { RegistryEntry } from '../source'",
    ...(imports.length > 0 ? ['', ...imports] : []),
    '',
    'export const registry: readonly RegistryEntry[] = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

function main() {
  const { check, root } = parseArgs(process.argv.slice(2))
  const target = join(root, REGISTRY)
  const paths = recordPaths(join(root, DATA))
  const expected = render(paths)
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null

  if (check) {
    if (current === expected) return
    const problem = current === null ? 'is missing' : `doesn't match the files in ${DATA}`
    process.stderr.write(`${REGISTRY} ${problem}. Write it with: ${COMMAND}\n`)
    process.exitCode = 1
    return
  }

  if (current !== expected) {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, expected)
  }
  process.stdout.write(`Content registry: ${paths.length} records.\n`)
}

main()
